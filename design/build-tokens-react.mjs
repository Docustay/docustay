// design/build-tokens-react.mjs — design/tokens.kit2.json → webreact/src/styles/theme.css
//
// ★ A SEPARATE generator on purpose (specs/react-rebuild DESIGN-TOKENS R-17d): design/build-tokens.mjs
//   generates the LIVE Svelte app's tokens.css, and a change to it would change the live product.
//   This one writes only the React theme. At cutover retirement (R12.4) this file replaces the old one.
//
// USAGE:  node design/build-tokens-react.mjs          (prints; writes nothing)
//         node design/build-tokens-react.mjs --write  (writes webreact/src/styles/theme.css)
//         import { buildReactTheme } — returns the css string, used by db/gates/design-tokens-react.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const THEME_PATH = path.join(ROOT, "webreact/src/styles/theme.css");

export function buildReactTheme(tokens = JSON.parse(readFileSync(path.join(ROOT, "design/tokens.kit2.json"), "utf8"))) {
  const L = [];
  L.push("/* GENERATED by design/build-tokens-react.mjs from design/tokens.kit2.json. DO NOT EDIT BY HAND. */");
  L.push("/* The React app's whole theme. Tailwind v4, CSS-first: no tailwind.config file exists. */");
  L.push('@import "tailwindcss" source("..");  /* scan webreact/src only */');
  L.push('@import "tw-animate-css";');
  L.push("/* ★★★ THE VARIANT BRIDGE. shadcn's components style themselves with data-open:, data-checked:, data-horizontal: …;");
  L.push("   this file defines each as a @custom-variant matching the attribute Radix actually emits (data-state=…, data-orientation=…).");
  L.push("   The Svelte app never imported its equivalent, and every Switch rendered as a white dot on white (F766). */");
  L.push('@import "shadcn/tailwind.css";');
  L.push("");
  for (const [family, weight, file] of tokens.fontFaces) {
    L.push(`@font-face { font-family: "${family}"; font-style: normal; font-weight: ${weight}; font-display: swap; src: url("/fonts/${file}") format("woff2"); }`);
  }
  L.push("");
  L.push("/* ═══ LAYER 1 — primitives. The only place a literal appears. Tailwind generates utilities from these names:");
  L.push("   bg-paper, text-ink, border-line, text-caption, rounded-card … ═══ */");
  L.push("@theme {");
  L.push("  --color-*: initial;");
  L.push("  --color-white: #FFFFFF;");
  L.push("  --color-black: #000000;");
  L.push("  --color-transparent: transparent;");
  L.push("  --color-current: currentColor;");
  for (const [k, v] of Object.entries(tokens.color)) L.push(`  --color-${k}: ${v};`);
  L.push(`  --font-sans: ${tokens.font.sans};`);
  L.push(`  --font-figure: ${tokens.font.figure};`);
  for (const [k, [size, lh]] of Object.entries(tokens.text)) { L.push(`  --text-${k}: ${size};`); L.push(`  --text-${k}--line-height: ${lh};`); }
  for (const [k, v] of Object.entries(tokens.radius)) L.push(`  --radius-${k}: ${v};`);
  for (const [k, v] of Object.entries(tokens.shadow ?? {})) L.push(`  --shadow-${k}: ${v};`);
  L.push("}");
  L.push("");
  L.push("/* ═══ LAYER 2 — sizes and motion, read as h-(--size-row), w-(--size-sidebar), duration-(--motion-base) ═══ */");
  L.push(":root {");
  for (const [k, v] of Object.entries(tokens.size)) L.push(`  --size-${k}: ${v};`);
  for (const [k, v] of Object.entries(tokens.motion)) L.push(`  --motion-${k}: ${v};`);
  L.push("");
  L.push("  /* shadcn's semantic names, pointed at the primitives (DESIGN-TOKENS §3.2). ★ --accent is the SUBTLE hover surface");
  L.push("     in shadcn, not the brand (R-17c): the brand is --primary. */");
  const sem = {
    background: "paper", foreground: "ink", card: "surface", "card-foreground": "ink", popover: "surface", "popover-foreground": "ink",
    primary: "brand", "primary-foreground": "surface", secondary: "surface", "secondary-foreground": "ink-2",
    muted: "mute-bg", "muted-foreground": "mute", accent: "brand-soft", "accent-foreground": "brand",
    destructive: "bad", border: "line", input: "line", ring: "brand",
    sidebar: "surface", "sidebar-foreground": "ink-2", "sidebar-primary": "brand", "sidebar-primary-foreground": "surface",
    "sidebar-accent": "brand-soft", "sidebar-accent-foreground": "brand", "sidebar-border": "line", "sidebar-ring": "brand",
    "chart-1": "brand", "chart-2": "ok", "chart-3": "warn", "chart-4": "bad", "chart-5": "mute",
  };
  for (const [k, v] of Object.entries(sem)) L.push(`  --${k}: var(--color-${v});`);
  L.push("");
  L.push("  /* ★ PORTAL/LEGACY BARE-NAME COMPATIBILITY (F-design-tokens-react-check3, 30 Sep 2026): the client");
  L.push("     portal and several components were ported from the old Svelte app's markup, which referenced");
  L.push("     these bare custom properties directly. The old app's design/tokens.json §semantic defined them —");
  L.push("     this app's token set never carried that layer over, so every reference below resolved to nothing.");
  L.push("     Bridging them here (rather than rewriting every portal file) keeps the fix centralised and undoes");
  L.push("     zero of the already-correct --color-* usage elsewhere. */");
  const bareAlias = {
    ink: "ink", "ink-2": "ink-2", mute: "mute", paper: "paper", surface: "surface", line: "line", hair: "hair",
    ok: "ok", warn: "warn", bad: "bad", danger: "danger-500",
    "ok-soft": "ok-soft", "warn-soft": "warn-soft", "bad-soft": "bad-soft", "bad-border": "bad-border", "bad-bg": "bad-bg",
    "chip-neutral-bg": "chip-neutral-bg", "chip-neutral-ink": "chip-neutral-ink",
    "ink-muted": "structure-600", "ink-faint": "structure-550",
    "surface-raised": "structure-0", "surface-sunken": "structure-50",
    "line-soft": "structure-150", "line-strong": "structure-300",
    "notice-wash": "warning-25", "notice-ink": "warning-800",
    "primary-wash": "action-50", "primary-edge": "action-200",
    "chip-ok-bg": "success-50", "chip-ok-ink": "success-700",
    "chip-warn-bg": "warning-50", "chip-warn-ink": "warning-700",
    "chip-bad-bg": "danger-50", "chip-bad-ink": "danger-700",
  };
  for (const [k, v] of Object.entries(bareAlias)) L.push(`  --${k}: var(--color-${v});`);
  L.push("  --chip-h: 24px; --chip-fs: 13px; --chip-fw: 500;");
  L.push(`  --radius: ${tokens.radius.control};`);
  L.push("}");
  L.push("");
  L.push("@theme inline {");
  for (const k of Object.keys(sem)) L.push(`  --color-${k}: var(--${k});`);
  L.push("  --radius-sm: calc(var(--radius) - 2px);");
  L.push("  --radius-md: var(--radius);");
  L.push("  --radius-lg: calc(var(--radius) + 2px);");
  L.push("  --radius-xl: calc(var(--radius) + 4px);");
  L.push("}");
  L.push("");
  L.push("@layer base {");
  L.push("  * { border-color: var(--color-line); outline-color: color-mix(in oklch, var(--color-brand) 50%, transparent); }");
  L.push("  /* ★ the maintainer, 29 Sep 2026 (F812) — the whole-page-scroll bug. Shell.jsx's root is `h-dvh overflow-hidden`,");
  L.push("     which should make ONLY <main> scroll — but nothing here stopped html/body THEMSELVES from growing");
  L.push("     and scrolling if that root div is ever, even transiently, taller than the viewport (a `dvh`-unit");
  L.push("     recalculation lag on resize is a known cross-browser quirk). html/body pinned to the real viewport");
  L.push("     height with their own overflow:hidden is the standard app-shell backstop — it makes a page-level");
  L.push("     scroll structurally impossible regardless of any transient content-height quirk upstream. ★★★ THIS");
  L.push("     LINE MUST STAY HERE, IN THE GENERATOR — a hand-edit to the generated theme.css alone is silently");
  L.push("     reverted by the next `--write` run, which is exactly how this rule went missing once already. */");
  L.push("  html, body { height: 100%; overflow: hidden; background: var(--color-paper); color: var(--color-ink); }");
  L.push("  body { margin: 0; font-family: var(--font-sans); font-size: var(--text-body); line-height: var(--text-body--line-height); -webkit-font-smoothing: antialiased; }");
  L.push("  [data-font=\"fraunces\"] { font-family: var(--font-figure); font-variant-numeric: tabular-nums; }");
  L.push("  ::placeholder { color: var(--color-placeholder); }");
  L.push("}");
  L.push("");
  L.push("/* The content column's per-navigation rise (webui Shell.svelte: 160ms fade + 4px rise, in only). */");
  L.push("@keyframes ks-rise { from { opacity: 0; transform: translateY(4px); } to { opacity: 1; transform: none; } }");
  L.push("");
  L.push("/* ★ ONE reduced-motion switch for every animation, including ones not written yet (webui app.css D6). */");
  L.push("@media (prefers-reduced-motion: reduce) {");
  L.push("  *, *::before, *::after { animation-duration: 0.01ms !important; animation-iteration-count: 1 !important; transition-duration: 0.01ms !important; scroll-behavior: auto !important; }");
  L.push("}");
  return L.join("\n") + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = buildReactTheme();
  if (process.argv.includes("--write")) { writeFileSync(THEME_PATH, css); console.log("wrote", path.relative(ROOT, THEME_PATH), css.length, "bytes"); }
  else process.stdout.write(css);
}
