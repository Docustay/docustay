/**
 * ★★★ THE SETTING KEY FOR ONE AUTOMATION, IN ONE PLACE. `automations.<key>_enabled`.
 *   Spelled by a function rather than written out at each call site, so the workflow (which reads
 *   it from n8n), the settings screen (which writes it) and the key catalogue (which validates it)
 *   cannot disagree about the string. **A per-tenant flag that three components spell differently
 *   is a flag that is always off somewhere.**
 *
 * ★★★ THE DOTS IN `key` ARE FLATTENED, AND WITHOUT THAT **THE DATABASE REFUSES EVERY ONE OF THESE.**
 *     `keystone.tenant_setting` carries a CHECK — `tenant_setting_key_shape` — of
 *     `^[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*$`: **EXACTLY ONE DOT.** An automation's key is itself
 *     dotted (`booking.confirmation`), so the old spelling produced
 *     `automations.booking.confirmation.enabled` — three dots — and all eight were unstorable.
 *   ★★ MEASURED 2026-09-16 by `db/gates/setting-catalogue.mjs` in the FINAL suite run:
 *      *"8 declared key(s) the DATABASE would refuse."* It had been true since A9.1, and the
 *      automations screen built on top of it would have thrown on every toggle — a working page, a
 *      working route, and a constraint underneath refusing all of it.
 *   ★ THIS IS WHY THE FUNCTION EXISTS. One edit here fixes the catalogue, the settings screen and
 *     the workflow at once; eight hand-written strings would have been eight separate fixes and at
 *     least one missed.
 */
export const automationSettingKey = (key) => `automations.${String(key).replace(/\./g, "_")}_enabled`;
