// ═══════════════════════════════════════════════════════════════════════════════════════════════
// A9.1 — THE AUTOMATION CATALOGUE. **ONE WORKFLOW PER AUTOMATION FOR THE WHOLE PLATFORM.**
//
// STAGE 20.20 — REWRITTEN FROM EVENT-AUTOMATION-MAP.md (25 Sep 2026). Every automation is now
// a row in the map with runner N/Q/S/R and a Default value (ON, ON locked, OFF).
//
// ★★★ THIS IS THE SINGLE MOST IMPORTANT ARCHITECTURAL DECISION IN PART 4 [TY, RULED]:
//     **one n8n workflow per AUTOMATION, filtering by tenant — NEVER one workflow per tenant.**
//     Fifty tenants × twelve automations is 600 workflows nobody can maintain, nobody can upgrade
//     atomically, and nobody can reason about when one of them starts failing.
//   ★★ SO THE PER-TENANT FLAG LIVES IN `tenant_setting` AND **n8n READS IT**. The workflow is
//      common; the decision to run for a given practice is data. That is what makes turning a
//      notification off *a setting that toggles* rather than a code change and a deploy.
//
// ★★★ AND THE LINE BETWEEN WHAT n8n MAY OWN AND WHAT IT MAY NOT, WHICH IS SHARPER THAN A LIST:
//     **n8n may own anything whose failure is RECOVERABLE BY RETRY AND INVISIBLE TO THE PERSON WHO
//     CLICKED. It must never own anything that is part of the answer to a request, or that is the
//     only record that something happened.**
//   That principle produces the entries below, and it also decides the cases a list would miss:
//     · NEVER in-request — a workflow in the request path makes p99 somebody else's uptime.
//     · NEVER inside a transaction — it cannot join one. The EVENT is emitted in the transaction;
//       the REACTION is not.
//     · ★★★ NEVER AUTH MAIL. A security rule, not a preference: a sign-in link is a CREDENTIAL, and
//       if the mailbox is broken and password resets go through it, **nobody can get in to fix it.**
//     · NEVER the outbox itself — n8n is a SUBSCRIBER. A second event system is two systems holding
//       one fact, which is this project's most-repeated defect.
//     · NEVER anything that is the only record — if the sole evidence a client was told something
//       lives in an n8n execution log, it is not in the product.
//
// ★★ TWO PLACES TY'S LINE MOVED, AND BOTH ARE HONOURED HERE:
//   1 · ★★★ INVOICE AND RECEIPT EMAIL ARE **NOT** n8n's, even though they look exactly like a
//       notification. An invoice is **a financial document being delivered**, and `email_delivery`
//       is the record that it was. A toggle that can silently stop invoices going out is a toggle
//       nobody should be given. **n8n sends the CHASE, not the INVOICE** — which is why
//       `invoice.overdue.chase` is here and no `invoice.send` is.
//   2 · ★ PROVISIONING STEPS ARE NOT AUTOMATIONS. They are a state machine with a real handoff. A
//       tenant half-provisioned because a workflow was toggled off is not a recoverable failure.
//
// ★ NOTHING IS IMPORTED HERE, ON PURPOSE — the settings screen reads this in a browser.
// ═══════════════════════════════════════════════════════════════════════════════════════════════

